!> Usage:
!>    wt.x                      -> reads wt.in (default)
!>    wt.x -in my_calc.in       -> reads my_calc.in
!>    wt.x -i / -inp / -input   -> same as -in
!>    wt.x my_calc.in           -> bare file name is also accepted
!>    wt.x -h / --help          -> print usage and exit
!>
!> Other source files only need one of:
!>    use cmdline, only : infilename            ! use the variable
!>    use cmdline, only : get_input_filename    ! or call the function
!>
!> parse_command_line() must be called once, early in main.f90.
module cmdline
   implicit none
   private

   integer, parameter, public :: MAXFNAME = 256
   character(len=MAXFNAME), public, save :: infilename = 'wt.in'

   public :: parse_command_line
   public :: get_input_filename

contains

   !> Return the input file name (default 'wt.in', or whatever -in set).
   function get_input_filename() result(fname)
      character(len=MAXFNAME) :: fname
      fname = infilename
   end function get_input_filename

   !> Parse the command line and set infilename.
   subroutine parse_command_line()
      integer :: i, narg
      character(len=MAXFNAME) :: arg

      narg = command_argument_count()
      i = 1
      do while (i <= narg)
         call get_command_argument(i, arg)
         select case (trim(arg))
         case ('-in', '-i', '-inp', '-input', '--input')
            if (i < narg) then
               i = i + 1
               call get_command_argument(i, infilename)
            else
               write(*, '(a)') 'ERROR: option '//trim(arg)//' needs a file name'
               call print_usage()
               stop 1
            end if
         case ('-h', '-help', '--help')
            call print_usage()
            stop 0
         case default
            if (arg(1:1) /= '-') then
               infilename = arg        ! bare file name
            else
               write(*, '(a)') 'ERROR: unknown option '//trim(arg)
               call print_usage()
               stop 1
            end if
         end select
         i = i + 1
      end do
   end subroutine parse_command_line

   subroutine print_usage()
      write(*, '(a)') 'Usage: wt.x [-in input_file]'
      write(*, '(a)') '   -in, -i, -inp, -input  FILE   input file (default: wt.in)'
      write(*, '(a)') '   -h, --help                    show this message'
   end subroutine print_usage

end module cmdline